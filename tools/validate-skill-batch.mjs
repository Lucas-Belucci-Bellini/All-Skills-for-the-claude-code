#!/usr/bin/env node
import assert from "node:assert/strict";
import { promises as fs } from "node:fs";
import path from "node:path";
const root=process.cwd();
const manifestArg=process.argv[2];
if(!manifestArg) throw new Error("Usage: node tools/validate-skill-batch.mjs <manifest.json>");
const manifest=JSON.parse(await fs.readFile(path.resolve(root,manifestArg),"utf8"));
const read=(p)=>fs.readFile(path.join(root,p),"utf8");
const batch=manifest.skills;
const expectedBatchSize=manifest.batch_size ?? 25;
assert.ok(Array.isArray(batch)&&batch.length===expectedBatchSize,`manifest must contain exactly ${expectedBatchSize} skills`);
assert.equal(new Set(batch.map(s=>s.name)).size,expectedBatchSize,"duplicate names in manifest");
const catalog=JSON.parse(await read("SKILL_LIBRARY_CATALOG.json"));
assert.equal(catalog.unique_skills,manifest.milestone_total,"catalog total mismatch");
assert.equal(catalog.skills.length,manifest.milestone_total,"catalog entry count mismatch");
assert.equal(new Set(catalog.skills.map(s=>s.name)).size,manifest.milestone_total,"catalog names not unique");
assert.equal(catalog.target,manifest.long_term_target,"long-term target mismatch");
assert.equal(catalog.remaining,manifest.long_term_target-manifest.milestone_total,"remaining count mismatch");
assert.equal(catalog.skills.filter(s=>s.origin==="new-authored").length,manifest.authored_count,"authored count mismatch");
assert.equal(catalog.skills.filter(s=>s.origin==="existing").length,manifest.retained_count,"retained count mismatch");
const byName=new Map(catalog.skills.map(s=>[s.name,s]));
const categories=new Map();
for(const s of catalog.skills)categories.set(s.category,(categories.get(s.category)||0)+1);
assert.equal([...categories.values()].reduce((a,b)=>a+b,0),manifest.milestone_total,"category counts do not reconcile");
for(const item of batch){
 const record=byName.get(item.name);
 assert.ok(record,item.name+": missing catalog record");
 assert.equal(record.origin,"new-authored",item.name+": wrong origin");
 assert.equal(record.source_path,item.source_path,item.name+": wrong canonical path");
 assert.equal(record.category,item.category,item.name+": wrong category");
 const src=await read(item.source_path);
 const bundle=await read("plugins/all-skills-collection/skills/"+item.name+"/SKILL.md");
 assert.equal(src,bundle,item.name+": source/bundle bytes differ");
 const fm=/^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(src);
 assert.ok(fm,item.name+": missing frontmatter");
 const nm=/^name:\s*(.*?)\s*$/m.exec(fm[1]);
 const dm=/^description:\s*(.*?)\s*$/m.exec(fm[1]);
 const unquote=v=>v?.replace(/^["']|["']$/g,"");
 assert.equal(unquote(nm?.[1]),item.name,item.name+": frontmatter name mismatch");
 assert.ok(unquote(dm?.[1])?.length>=35,item.name+": description too short");
 for(const h of ["# ","## Purpose","## Required inputs","## Validation checklist","## Required output","## Boundaries and failure handling","## Trigger examples"])assert.ok(src.includes(h),item.name+": missing "+h);
 assert.ok(/^## (?:Workflow|.*\\bprotocol)$/im.test(src),item.name+": missing workflow/protocol section");
 assert.ok((src.match(/^\d+\.\s/gm)||[]).length>=4,item.name+": workflow too short");
 assert.ok((src.match(/^- \[ \] /gm)||[]).length>=4,item.name+": checklist too short");
 assert.match(src, /^- \*\*Positive:\*\*/m,item.name+": positive trigger missing");
 assert.match(src, /^- \*\*Negative:\*\*/m,item.name+": negative trigger missing");
}
const plugin=JSON.parse(await read("plugins/all-skills-collection/.claude-plugin/plugin.json"));
const market=JSON.parse(await read(".claude-plugin/marketplace.json"));
const entry=market.plugins.find(s=>s.name==="all-skills-collection");
assert.equal(plugin.version,manifest.plugin_version,"plugin version mismatch");
assert.equal(entry?.version,plugin.version,"marketplace/plugin versions differ");
assert.match(plugin.description,new RegExp(manifest.milestone_total+" distinct skills"));
assert.match(entry.description,new RegExp(manifest.milestone_total+" distinct skills"));
assert.ok((await read("README.md")).includes("currently packages "+manifest.milestone_total+" distinct skills"),"root README count mismatch");
assert.ok((await read("plugins/all-skills-collection/README.md")).includes("**"+manifest.milestone_total+" distinct skills**"),"plugin README count mismatch");
const roadmap=await read("SKILL_GROWTH_ROADMAP.md");
const fmt=n=>n.toLocaleString("en-US");
assert.ok(roadmap.includes("**Current draft inventory:** "+fmt(manifest.milestone_total)+" distinct skills ("+fmt(manifest.authored_count)+" authored + "+fmt(manifest.retained_count)+" retained/imported)"),"roadmap inventory mismatch");
assert.ok(roadmap.includes("**Remaining to long-term target:** "+fmt(manifest.long_term_target-manifest.milestone_total)),"roadmap remaining mismatch");
assert.ok(roadmap.includes("| "+manifest.milestone_total+" | "+manifest.milestone_total+" |"),"checkpoint missing");
const markdown=await read("SKILL_LIBRARY_CATALOG.md");
const headingCounts=[...markdown.matchAll(/^### .+ \((\d+)\)$/gm)].map(m=>Number(m[1]));
assert.equal(headingCounts.reduce((a,b)=>a+b,0),manifest.milestone_total,"Markdown category headers mismatch");
assert.ok(markdown.includes("contains "+manifest.milestone_total+" distinct skills"),"Markdown total mismatch");
console.log("PASS: "+batch.length+" new skills; "+manifest.milestone_total+" unique catalog entries; source/bundle parity, frontmatter, workflow sections and metadata validated.");
